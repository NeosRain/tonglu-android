package cn.tonglu.app.data

/**
 * 「上完课」时那句小字文案。
 *
 * 之前这里写的是「已上完 N 节，上完的课自动隐藏」——像产品说明书，不像人话。
 * 现在换成两句式：前面保留信息（已上完几节），后面接一句有梗的。
 *
 * 文案来源：GitHub 上没有现成可用的中文「下课」梗库（相关仓库都是表情包、
 * Minecraft 梗体中文、程序员段子），一言 API 的「抖机灵」分类实测质量参差、
 * 重复率高且偶有不适内容，所以不联网，改为本地池：
 * 参考了网上常见的校园/摸鱼/摆烂口吻自己攒的，离线可用、点一下换一条。
 */
object ClassOverLines {

    /** 今天的课全上完了 —— 「放学」口吻 */
    val ALL_DONE: List<String> = listOf(
        "课全清空，剩下的时间归你",
        "上完啦，快耍起～",
        "课本合上，人生开启",
        "今日学业进度 100%，请查收自由",
        "全上完了，图书馆还是食堂，你说话",
        "宣布：今天，正式下课",
        "接下来这几个小时，谁也别想管你",
        "课都上完了，还坐这儿干嘛",
        "今日任务完毕，去吃口热的",
        "书包一甩，这就是自由的形状",
        "上完课的人，连风都是顺的",
        "别卷了，今天已经够本了",
        "下课铃一响，人生重新开始",
        "书念完了，该去遛遛自己了",
        "今天到此为止，明天再说",
        "笔帽一盖，收工",
        "这会儿的太阳，是给你留的",
        "自由时间已到账，请及时消费",
    )

    /** 还有课，中间空档 —— 「课间」口吻 */
    val BETWEEN: List<String> = listOf(
        "这节上完，先瘫一会儿",
        "课间十分钟，快乐两小时",
        "歇会儿，下一节还在等你",
        "上完一节是一节，稳住",
        "先喘口气，书包先别背",
        "这一节结束了，下一节还远吗",
        "课间放空，是正经事",
        "进度条往前挪了一点，值得庆祝",
        "趁现在，赶紧摸会儿鱼",
        "凳子坐麻了，起来走两步",
        "水杯该续上了",
        "别急着走，下一节是你的",
        "这节过去了，你比刚才强一点",
        "效率呢？不存在的，先歇",
        "课间就该干点没用的",
        "还有课，但先不管它",
        "上完的这节，就当没上过（不是）",
        "歇够了再战，不差这几分钟",
    )

    /**
     * 取一句。
     *
     * @param allDone 今天是否已经全上完（决定用哪一组口吻）
     * @param tick 递增的序号，换一条就 +1；内部对池子长度取模，越界也不会崩
     */
    fun pick(allDone: Boolean, tick: Int): String {
        val pool = if (allDone) ALL_DONE else BETWEEN
        val index = ((tick % pool.size) + pool.size) % pool.size
        return pool[index]
    }

    /** 供自检用：文案总数 */
    val count: Int get() = ALL_DONE.size + BETWEEN.size
}
